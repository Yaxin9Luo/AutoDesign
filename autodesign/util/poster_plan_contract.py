def _contract_source_visual_flags(rec: dict[str, Any]) -> set[str]:
    flags: set[str] = set()
    for key in ("crop_quality_flags", "curation_flags", "severe_crop_flags"):
        for raw in list(rec.get(key) or []):
            flag = str(raw or "").strip()
            if flag:
                flags.add(flag)
    material = rec.get("material_quality")
    if isinstance(material, dict):
        for raw in list(material.get("warnings") or []):
            flag = str(raw or "").strip()
            if flag:
                flags.add(flag)
    return flags


def _contract_source_visual_has_weak_selected_flags(rec: dict[str, Any], flags: set[str]) -> bool:
    return bool(_contract_source_visual_weak_reasons(rec, flags))


def _contract_source_visual_weak_reasons(rec: dict[str, Any], flags: set[str]) -> list[str]:
    reasons: list[str] = []
    score = _safe_int(rec.get("visual_score"), 0)
    role = str(rec.get("visual_role") or "").strip().lower()
    strong_captioned = _contract_source_visual_has_captioned_group(rec)
    if "low_caption_confidence" in flags and (not strong_captioned or score < 72):
        reasons.append("selected_weak_caption")
    if "no_caption" in flags and not strong_captioned:
        reasons.append("selected_missing_caption")
    if "source_page_unknown" in flags and not strong_captioned:
        reasons.append("selected_source_page_unknown")
    low_detail_is_weak = (
        score < 72
        or not strong_captioned
        or "no_caption" in flags
        or role not in {"method", "table", "evidence"}
    )
    if "low_detail_visual_content" in flags and low_detail_is_weak:
        reasons.append("selected_low_detail_weak_crop")
    mostly_white_is_weak = (
        score < 72
        or "no_caption" in flags
        or low_detail_is_weak
        or ("low_caption_confidence" in flags and not strong_captioned)
    )
    if "mostly_white_visual" in flags and mostly_white_is_weak:
        reasons.append("selected_mostly_white_weak_crop")
    edge_whitespace_is_weak = (
        score < 68
        or low_detail_is_weak
        or ("low_caption_confidence" in flags and not strong_captioned)
        or (role not in {"method", "table", "evidence"} and not (strong_captioned and score >= 72))
    )
    if "high_edge_whitespace" in flags and edge_whitespace_is_weak:
        reasons.append("selected_edge_whitespace_weak_crop")
    return reasons


def _contract_source_visual_has_captioned_group(rec: dict[str, Any]) -> bool:
    if not (
        rec.get("captioned_source_group")
        or rec.get("source_group_id")
        or rec.get("source_group_label")
        or rec.get("source_group_caption")
    ):
        return False
    caption = " ".join(
        str(rec.get(key) or "")
        for key in ("caption", "caption_text", "caption_full", "caption_short", "source_group_caption", "title")
    ).strip()
    return bool(caption)


