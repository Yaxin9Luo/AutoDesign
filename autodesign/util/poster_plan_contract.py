            "columns. Each column contains one to three .poster-section blocks with section "
            "bars, wide figures/tables, formulas, compact comparison table rows, and short local prose. "
            "Use a short inline lead-key phrase as <strong class=\"lead-key\">...</strong> only inside normal "
            "body/readout/table prose, without data-block-id on the inline strong element. "
            "One or two sections per column is preferred; three is the maximum. Do not "
            "create six equal flow-panel cards, four-section columns, stretched bottom-fill "
            "sections, or panel_content_plan slots."
