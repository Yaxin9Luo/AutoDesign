def _contract_layout_slot_contract(
    *,
    brief: dict[str, Any],
    canvas_plan: dict[str, Any],
    rendered_layers: dict[str, dict[str, Any]],
    layout_archetype: str,
    reference_profile: str,
    sections: list[dict[str, Any]],
    selected_ids: list[str],
    native_information_targets: dict[str, Any],
    content_fill_targets: dict[str, Any],
) -> dict[str, Any]:
    canvas = canvas_plan.get("canvas") if isinstance(canvas_plan.get("canvas"), dict) else {}
    cw = _safe_int(canvas.get("w_px") or canvas.get("w"), 3072)
    ch = _safe_int(canvas.get("h_px") or canvas.get("h"), 2172)
    if cw <= 0 or ch <= 0:
        return {}
    landscape = cw >= ch
    if not landscape or not _is_allowed_academic_archetype(layout_archetype):
        return {}

    margin = max(18, round(min(cw, ch) * 0.022))
    gutter = max(12, round(min(cw, ch) * 0.014))
    grid = _resolve_main_panel_grid(canvas_plan, layout_archetype)
    grid_family = str(grid.get("family") or "")
    title_h = (
        max(140, min(round(ch * 0.11), round(ch * 0.13)))
        if grid_family == _CVPR_GRID_FAMILY
        else max(84, min(round(ch * 0.12), round(ch * 0.18)))
    )
    cols = max(3, _safe_int(grid.get("cols"), 3))
    rows = max(2, _safe_int(grid.get("rows"), 2))
    main_panel_count = cols * rows
    separate_synthesis_strip = main_panel_count <= 6 and grid_family != _CVPR_GRID_FAMILY
    bottom_h = max(68, min(round(ch * 0.09), round(ch * 0.14))) if separate_synthesis_strip else 0
    main_y = margin + title_h + gutter
    bottom_gap = gutter if separate_synthesis_strip else 0
    main_h = max(180, ch - main_y - bottom_h - margin - bottom_gap)
    col_w = (cw - margin * 2 - gutter * (cols - 1)) // cols
    row_h = max(80, (main_h - gutter * (rows - 1)) // rows)

    section_roles = _section_roles_for_grid(
        sections,
        main_panel_count,
        include_synthesis=not separate_synthesis_strip,
        grid_family=grid_family,
    )

    slots: list[dict[str, Any]] = [
        {
            "slot_id": "title_meta",
            "role": "identity_header",
            "bbox": {"x": margin, "y": margin, "w": cw - margin * 2, "h": title_h},
            "required": True,
            "panel_role": "identity_header",
            "content_policy": (
                "Compact paper identity only: exactly these three visible paper-identity rows for title, authors, "
                "and plain-text school/institution/company names. Do not add a fourth header/meta/subtitle "
                "row, side identity rail, venue/archive/citation/contact/project/code/resource text, logos, icons, QR codes, badges, "
                "a thesis, right-side summary, slogan, tagline, Core idea, Poster focus, method/result "
                "readout, source figure/table, or generic source-backed descriptor."
            ),
            "child_lanes": _title_lanes(cw - margin * 2, title_h),
        }
    ]

    visual_cursor = 0
    used_visual_ids: set[str] = set()
    selected_set = {str(item) for item in selected_ids}
    for idx, section_role in enumerate(section_roles):
        role = str(section_role.get("slot_id") or f"panel_{idx + 1:02d}")
        title = str(section_role.get("title") or role.replace("_", " ").title())
        row = idx // cols
        bbox = _main_slot_bbox(
            idx,
            family=grid_family,
            margin=margin,
            gutter=gutter,
            main_y=main_y,
            main_h=main_h,
            col_w=col_w,
            row_h=row_h,
            cols=cols,
        )
        visual_ids: list[str] = []
        visual_aspect = 0.0
        visual_layout_variant = ""
        section_visuals = [
            str(item)
            for item in (section_role.get("visual_ids") or [])
            if str(item or "") in selected_set
        ]
        visual_capacity = _slot_visual_capacity(role)
        for candidate in section_visuals:
            if candidate not in used_visual_ids and len(visual_ids) < visual_capacity:
                visual_ids.append(candidate)
        if selected_ids and _role_should_receive_visual(role):
            while len(visual_ids) < visual_capacity:
                next_visual = _next_selected_visual(selected_ids, used_visual_ids | set(visual_ids), visual_cursor)
                if not next_visual:
                    break
                visual_ids.append(next_visual)
                visual_cursor = selected_ids.index(next_visual) + 1 if next_visual in selected_ids else visual_cursor + 1
        if visual_ids:
            used_visual_ids.update(visual_ids)
            visual_aspect = _visual_aspect_for_id(visual_ids[0], rendered_layers)
            visual_layout_variant = _visual_layout_variant(
                role,
                visual_aspect,
                variant_seed=idx,
                slot_w=bbox["w"],
                slot_h=bbox["h"],
            )
        elif selected_ids and _role_should_receive_visual(role):
            next_visual = _next_selected_visual(selected_ids, used_visual_ids, visual_cursor)
            if next_visual:
                visual_ids = [next_visual]
                visual_cursor = selected_ids.index(next_visual) + 1 if next_visual in selected_ids else visual_cursor + 1
                used_visual_ids.update(visual_ids)
                visual_aspect = _visual_aspect_for_id(visual_ids[0], rendered_layers)
                visual_layout_variant = _visual_layout_variant(
                    role,
                    visual_aspect,
                    variant_seed=idx,
                    slot_w=bbox["w"],
                    slot_h=bbox["h"],
                )
        slots.append({
            "slot_id": role,
            "role": role,
            "panel_role": role,
            "title": title,
            "bbox": bbox,
            "required": True,
            "visual_ids": visual_ids,
            "source_aspect": round(visual_aspect, 4) if visual_aspect > 0 else None,
            "visual_layout_variant": visual_layout_variant or None,
            "content_policy": (
                "Use this panel as one grid cell in the poster body, not as a set of "
                "absolute child boxes. Inside the panel, designer-authored CSS owns "
                "natural-flow DOM units: a heading, then one direct-child "
                ".figure-flow-unit/.source-flow-unit per source figure/table when "
                "visual_ids are available. Each unit treats the bound source image/table "
                "itself as the normal-flow object, not as content inserted into an empty "
                "placeholder/bbox. Each unit contains the bound source asset, "
                "compact local readout text, optional native bands/labels, and a takeaway. "
                "Text should explain that unit's visual asset rather than become the main "
                "panel mass. The child_lanes are content/capacity hints only, not rectangles "
                "to copy. When the panel has visual_ids, bind each figure/table with "
                "data-source-id or data-layer-id and let the unit's nearby text wrap "
                "around it with float/shape-outside when appropriate."
            ),
            "child_lanes": _main_panel_lanes(
                bbox["w"],
                bbox["h"],
                visual_ids=visual_ids,
                visual_aspect=visual_aspect,
                layout_variant=visual_layout_variant,
            ),
        })

    if separate_synthesis_strip:
        bottom_y = min(ch - margin - bottom_h, main_y + row_h * rows + gutter * rows)
        slots.append({
            "slot_id": "synthesis_takeaway",
            "role": "synthesis_takeaway",
            "panel_role": "synthesis_takeaway",
            "bbox": {"x": margin, "y": bottom_y, "w": cw - margin * 2, "h": ch - bottom_y - margin},
            "required": True,
            "content_policy": "Bottom synthesis strip with compact source-backed takeaways and a tiny provenance line.",
            "child_lanes": _synthesis_lanes(cw - margin * 2, ch - bottom_y - margin),
        })

    plan_contract = _panel_content_plan_contract(slots)
    authoring_blueprint = _panel_authoring_blueprint(slots)
    return {
        "version": 1,
        "profile": reference_profile or "academic_paper_poster",
        "orientation": "landscape",
        "layout_archetype": layout_archetype,
        "grid": grid,
        "mode": "authored_css_poster",
        "slots": slots,
        "child_lane_contract": {
            "coordinate_system": "slot_local_capacity_hints",
            "required_lane_ratio": 0.0,
            "child_rule": (
                "child_lanes[] entries are planner-facing content and capacity hints. "
                "They do not own geometry. Designer-authored HTML/CSS may realize them "
                "as semantic regions, grid areas, normal-flow sections, or figure/text "
                "wraps, while preserving source bindings."
            ),
        },
        "hard_rules": [
            "Use the fixed CVPR 84x42 landscape board as a CSS grid: identity header plus three body columns by two rows.",
            "Do not author panel roots or panel children with position:absolute/left/top/bottom/right geometry.",
            "Planner owns each panel's browser-native DOM flow; do not copy child_lanes as rectangles.",
            "Do not create empty visual placeholder boxes before inserting source assets; the source figure/table is the flow object inside its own source-flow unit.",
            "Use float/shape-outside inside each source flow unit so paragraphs wrap around the bound source visual/table.",
            "Use paper figures/tables as the dominant panel assets; text is short local readout/takeaway support, not the visual subject.",
            "For panels with source visuals/tables, place each as a bound figure/table near its local explanation/takeaway; preserve intrinsic aspect and avoid arbitrary cropping.",
            "If content does not fit, revise the authored HTML/CSS, shorten copy, or convert prose into native visual/table units; never rely on a later post-pass.",
        ],
        "min_panel_count": main_panel_count,
        "target_panel_count": main_panel_count,
        "max_panel_count": main_panel_count,
        "min_visible_words": native_information_targets.get("min_visible_words"),
        "target_visible_words": native_information_targets.get("target_visible_words"),
        "min_native_information_units": native_information_targets.get("min_native_information_units"),
        "target_native_information_units": native_information_targets.get("target_native_information_units"),
        "content_fill_contract": content_fill_targets,
        "panel_content_plan_contract": plan_contract,
        "designer_authoring_blueprint": authoring_blueprint,
    }


def _main_slot_bbox(
    idx: int,
    *,
    family: str,
    margin: int,
    gutter: int,
    main_y: int,
    main_h: int,
    col_w: int,
    row_h: int,
    cols: int,
) -> dict[str, int]:
    if family == _CVPR_GRID_FAMILY:
        # CVPR posters read as three vertical columns, not as a row-major tile
        # board. Each column stacks two large panels; the center column gives
        # the method/framework panel more height like human-authored posters.
        col = min(2, max(0, idx // 2))
        pos_in_col = idx % 2
        split = 0.50
        if col == 1:
            split = 0.62
        elif col == 2:
            split = 0.46
        top_h = max(80, round((main_h - gutter) * split))
        bottom_h = max(80, main_h - gutter - top_h)
        return {
            "x": margin + col * (col_w + gutter),
            "y": main_y if pos_in_col == 0 else main_y + top_h + gutter,
            "w": col_w,
            "h": top_h if pos_in_col == 0 else bottom_h,
        }
    col = idx % cols
    row = idx // cols
    return {
        "x": margin + col * (col_w + gutter),
        "y": main_y + row * (row_h + gutter),
        "w": col_w,
        "h": row_h,
    }


def _resolve_main_panel_grid(canvas_plan: dict[str, Any], layout_archetype: str) -> dict[str, Any]:
    body_grid = canvas_plan.get("body_grid") if isinstance(canvas_plan.get("body_grid"), dict) else {}
    family = str(body_grid.get("family") or canvas_plan.get("grid_family") or "").strip()
    cols = _safe_int(body_grid.get("cols"), 0)
    rows = _safe_int(body_grid.get("rows"), 0)
    allowed = {
        _CVPR_GRID_FAMILY: (3, 2),
    }
    if family in allowed:
        cols, rows = allowed[family]
    elif (cols, rows) not in {(3, 2), (4, 2), (3, 3)}:
        family, cols, rows = _CVPR_GRID_FAMILY, 3, 2
    if family == _CVPR_GRID_FAMILY:
        cols, rows = 3, 2
    else:
        family, cols, rows = _CVPR_GRID_FAMILY, 3, 2
    panel_count = cols * rows
    return {
        "family": family,
        "cols": cols,
        "rows": rows,
        "main_panel_count": panel_count,
        "min_main_panels": 6,
        "target_main_panels": panel_count,
        "max_main_panels": panel_count,
        "allowed_families": [_CVPR_GRID_FAMILY],
        "disallowed_families": ["2x1_wide", "3x2_landscape", "4x2_balanced", "3x3_landscape", "4x3_expanded"],
        "layout": "three_column_human_poster",
    }


def _section_roles_for_grid(
    sections: list[dict[str, Any]],
    panel_count: int,
    *,
    include_synthesis: bool,
    grid_family: str = "",
) -> list[dict[str, Any]]:
    roles: list[dict[str, Any]] = []
    used: set[str] = set()
    for section in sections:
        if not isinstance(section, dict):
            continue
        raw_id = str(section.get("section_id") or section.get("role") or section.get("title") or "").strip()
        slot_id = _normalize_slot_id(raw_id)
        if not slot_id or slot_id in {"identity_header", "title_meta"}:
            continue
        if slot_id == "synthesis_takeaway" and not include_synthesis:
            continue
        slot_id = _unique_slot_id(slot_id, used)
        used.add(slot_id)
        roles.append({
            "slot_id": slot_id,
            "title": str(section.get("title") or raw_id.replace("_", " ").title()),
            "visual_ids": [str(item) for item in (section.get("visual_ids") or []) if str(item or "").strip()],
        })
        if len(roles) >= panel_count:
            break

    if grid_family == _CVPR_GRID_FAMILY:
        roles = _order_cvpr_three_column_roles(roles, panel_count)
        used = {str(role.get("slot_id") or "") for role in roles}

    for slot_id, title in _fallback_panel_roles(include_synthesis=include_synthesis):
        if len(roles) >= panel_count:
            break
        if slot_id in used:
            continue
        used.add(slot_id)
        roles.append({"slot_id": slot_id, "title": title, "visual_ids": []})
    return roles[:panel_count]


def _order_cvpr_three_column_roles(roles: list[dict[str, Any]], panel_count: int) -> list[dict[str, Any]]:
    buckets: list[dict[str, Any] | None] = [None] * panel_count
    patterns = [
        ("motivation|introduction|background|overview|context", 0),
        ("problem|challenge|contribution|definition|scope", 1),
        ("method|framework|approach|model|architecture|pipeline", 2),
        ("mechanism|training|algorithm|objective|implementation|theory", 3),
        ("result|experiment|evaluation|benchmark|table|metric", 4),
        ("ablation|analysis|qualitative|robust|limitation|future|takeaway", 5),
    ]
    remaining: list[dict[str, Any]] = []
    for role in roles:
        haystack = " ".join(str(role.get(key) or "") for key in ("slot_id", "title")).lower()
        target_idx = None
        for pattern, idx in patterns:
            if re.search(pattern, haystack) and idx < panel_count and buckets[idx] is None:
                target_idx = idx
                break
        if target_idx is None:
            remaining.append(role)
        else:
            buckets[target_idx] = role
    for role in remaining:
        for idx in range(panel_count):
            if buckets[idx] is None:
                buckets[idx] = role
                break
    return [role for role in buckets if isinstance(role, dict)]


def _fallback_panel_roles(*, include_synthesis: bool) -> list[tuple[str, str]]:
    roles = [
        ("motivation_background", "Motivation / Background"),
        ("problem_contribution", "Problem / Contribution"),
        ("method_pipeline", "Method Pipeline"),
        ("model_mechanism", "Model / Mechanism"),
        ("results_table", "Benchmark / Results"),
        ("ablation_analysis", "Ablations / Analysis"),
    ]
    if include_synthesis:
        roles.append(("synthesis_takeaway", "Synthesis / Takeaway"))
    return roles


def _normalize_slot_id(value: str) -> str:
    clean = re.sub(r"[^a-z0-9]+", "_", str(value or "").strip().lower()).strip("_")
    return clean or "panel"


def _unique_slot_id(slot_id: str, used: set[str]) -> str:
    if slot_id not in used:
        return slot_id
    idx = 2
    while f"{slot_id}_{idx}" in used:
        idx += 1
    return f"{slot_id}_{idx}"


def _role_should_receive_visual(role: str) -> bool:
    role_l = str(role or "").lower()
    return any(token in role_l for token in (
        "motivation", "problem", "contribution", "method", "model",
        "architecture", "visual", "result", "evidence", "benchmark",
        "table", "ablation", "analysis", "qualitative", "limitation",
        "future",
    ))


def _slot_visual_capacity(role: str) -> int:
    role_l = str(role or "").lower()
    if any(token in role_l for token in ("result", "benchmark", "table", "ablation", "analysis", "evidence")):
        return 2
    if any(token in role_l for token in ("method", "model", "architecture", "pipeline", "qualitative")):
        return 2
    return 1


def _next_selected_visual(selected_ids: list[str], used: set[str], start_index: int) -> str:
    if not selected_ids:
        return ""
    for offset in range(len(selected_ids)):
        idx = (max(0, start_index) + offset) % len(selected_ids)
        candidate = selected_ids[idx]
        if candidate not in used:
            return candidate
    return ""


