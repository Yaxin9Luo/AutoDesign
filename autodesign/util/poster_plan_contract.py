def _layout_plan_summary(spec: Any) -> dict[str, Any]:
    spec_payload = spec.model_dump(mode="json") if hasattr(spec, "model_dump") else spec
    artifact = (spec_payload or {}).get("html_artifact") if isinstance(spec_payload, dict) else {}
    frames = artifact.get("frames") if isinstance(artifact, dict) else []
    slots: list[dict[str, Any]] = []
    archetype = ""
    for frame in frames or []:
        if not isinstance(frame, dict):
            continue
        plan = frame.get("layout_plan") if isinstance(frame.get("layout_plan"), dict) else {}
        if plan:
            archetype = str(plan.get("archetype") or archetype)
            slots.extend(slot for slot in (plan.get("slots") or []) if isinstance(slot, dict))
    slot_text = [
        " ".join(
            str(slot.get(key) or "")
            for key in ("slot_id", "role", "content_policy", "panel_job", "text_budget", "space_fill_policy")
        )
        for slot in slots
    ]
    main_slots = [slot for slot in slots if not _is_meta_contract_slot(slot)]
    return {
        "archetype": archetype,
        "slot_count": len(slots),
        "main_slot_count": len(main_slots),
        "slots_with_visual_ids": sum(1 for slot in slots if slot.get("visual_ids")),
        "slots_with_panel_jobs": sum(
            1 for slot in slots
            if slot.get("panel_job") or slot.get("text_budget") or slot.get("space_fill_policy")
        ),
        "slot_text": slot_text,
    }


def _is_meta_contract_slot(slot: dict[str, Any]) -> bool:
    blob = " ".join(
        str(slot.get(key) or "")
        for key in ("slot_id", "role", "panel_job", "content_policy", "space_fill_policy")
    ).lower()
    return any(token in blob for token in (
        "title", "header", "footer", "citation", "contact", "identity",
        "meta", "provenance", "watermark", "logo",
    ))


