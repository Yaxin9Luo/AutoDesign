def _dense_native_table_layer(layer: dict[str, Any]) -> bool:
    if _dense_source_table_crop_layer(layer):
        return False
    if str(layer.get("kind") or "").lower() == "table":
        return True
    return _dense_table_body_row_count(layer) > 0 and (
        _layer_identity(layer).startswith("ingest_table_")
        or _layer_source_id(layer).startswith("ingest_table_")
    )


def _dense_source_table_crop_layer(layer: dict[str, Any]) -> bool:
    if str(layer.get("table_visual_source") or "").lower() != "original_pdf_crop":
        return False
    has_crop_visual = bool(layer.get("src_path") or layer.get("image_size") or layer.get("path"))
    if not has_crop_visual:
        return False
    if layer.get("native_table_reconstruction"):
        return False
    return "ingest_table_" in _layer_identity(layer) or "ingest_table_" in _layer_source_id(layer)


def _dense_table_body_row_count(layer: dict[str, Any]) -> int:
    rows = layer.get("rows")
    if isinstance(rows, list) and rows:
        return len(rows)
    data = layer.get("table_data") or layer.get("data")
    if isinstance(data, dict):
        rows = data.get("rows") or data.get("body")
        if isinstance(rows, list) and rows:
            return len(rows)
    text = str(layer.get("text") or layer.get("content") or "")
    if "\n" in text:
        lines = [line for line in text.splitlines() if line.strip()]
        return max(0, len(lines) - 1)
    return 0


