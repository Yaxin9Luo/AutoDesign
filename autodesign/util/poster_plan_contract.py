def _role_visual_ids(
    role: str,
    selected_ids: list[str],
    visual_selection: dict[str, Any],
    rendered_layers: dict[str, dict[str, Any]],
    role_buckets: dict[str, Any],
    *,
    forbidden_source_ids: set[str] | None = None,
) -> list[str]:
    forbidden_source_ids = forbidden_source_ids or set()
    candidates = [str(v) for v in (role_buckets.get(role) or []) if str(v or "").strip()]
    if role == "evidence":
        candidates.extend(str(v) for v in (role_buckets.get("table") or []) if str(v or "").strip())
    selected = [
        vid for vid in selected_ids
        if (
            vid in candidates
            and _contract_source_id_allowed(vid, rendered_layers, forbidden_source_ids)
        )
    ]
    if selected:
        return selected[:4]
    records = visual_selection.get("visual_records") if isinstance(visual_selection.get("visual_records"), list) else []
    for record in records:
        if not isinstance(record, dict):
            continue
        layer_id = str(record.get("layer_id") or "")
        if not _contract_source_id_allowed(layer_id, rendered_layers, forbidden_source_ids):
            continue
        visual_role = str(record.get("visual_role") or rendered_layers.get(layer_id, {}).get("visual_role") or "")
        if layer_id and (visual_role == role or (role == "evidence" and visual_role == "table")):
            selected.append(layer_id)
    return selected[:4]


