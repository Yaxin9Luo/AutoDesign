def _source_asset_capacity_for_contract(
    canvas_plan: dict[str, Any],
    *,
    reference_profile: str,
    available_count: int,
) -> dict[str, int]:
    canvas = canvas_plan.get("canvas") if isinstance(canvas_plan.get("canvas"), dict) else {}
    preset_id = str(canvas_plan.get("preset_id") or "")
    cw = _safe_int(canvas.get("w_px") or canvas.get("w"), 0)
    ch = _safe_int(canvas.get("h_px") or canvas.get("h"), 0)
    ratio = (cw / float(ch)) if cw > 0 and ch > 0 else 0.0
    if reference_profile == _EDITORIAL_FLOW_PROFILE and (preset_id == "cvpr-landscape" or (ratio >= 1.75 and ch <= 1700)):
        target = 6
        primary = 6
        minimum = 5
        maximum = 8
    elif ch >= 2200 or (cw * ch) >= 7_000_000:
        target = 10
        primary = 7
        minimum = 6
        maximum = 12
    else:
        budget = canvas_plan.get("density_budget") if isinstance(canvas_plan.get("density_budget"), dict) else {}
        target = _safe_int(budget.get("target_visuals_max"), 8)
        primary = _safe_int(budget.get("target_visuals_min"), min(6, target))
        minimum = max(1, min(primary, _safe_int(budget.get("target_visuals_min"), primary)))
        maximum = target
    if available_count > 0:
        target = min(target, available_count)
        primary = min(primary, target)
        minimum = min(minimum, target)
        maximum = min(maximum, available_count)
    return {
        "target_visual_count": max(1, target),
        "primary_visual_count": max(1, primary),
        "min_visual_count": max(1, minimum),
        "max_visual_count": max(1, maximum),
    }


def _contract_supplemental_native_visual_tasks(
    brief: dict[str, Any],
    visual_selection: dict[str, Any],
) -> list[dict[str, Any]]:
    candidates = []
    for value in (
        visual_selection.get("supplemental_native_visual_tasks"),
        brief.get("supplemental_native_visual_tasks"),
        (brief.get("native_reconstruction_hints") or {}).get("supplemental_native_visual_tasks")
        if isinstance(brief.get("native_reconstruction_hints"), dict) else None,
    ):
        if isinstance(value, list) and value:
            candidates = value
            break
    out: list[dict[str, Any]] = []
    seen: set[str] = set()
    for item in candidates:
        if not isinstance(item, dict):
            continue
        task_id = str(item.get("task_id") or item.get("id") or item.get("kind") or "").strip()
        if not task_id:
            task_id = f"native_visual_task_{len(out) + 1:02d}"
        if task_id in seen:
            continue
        normalized = dict(item)
        normalized["task_id"] = task_id
        normalized["kind"] = str(normalized.get("kind") or "native_visual_unit")
        normalized.setdefault(
            "policy",
            "native editable HTML/SVG/table only; grounded in poster_content_brief and paper evidence; never use rejected source crops",
        )
        out.append(normalized)
        seen.add(task_id)
    return out


