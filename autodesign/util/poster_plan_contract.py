        claim_h = max(50, round(content_h * 0.16))
        caption_h = max(66, round(content_h * 0.22))
        native_h = max(56, round(content_h * 0.18))
        takeaway_h = max(50, round(content_h * 0.16))
        body_h = max(66, content_h - claim_h - caption_h - native_h - takeaway_h - gap * 4)
