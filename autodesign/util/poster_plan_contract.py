def _slot_authoring_blueprint(slot: dict[str, Any]) -> dict[str, Any]:
    slot_id = str(slot.get("slot_id") or "").strip()
    if not slot_id:
        return {}
    lanes = [lane for lane in (slot.get("child_lanes") or []) if isinstance(lane, dict)]
    visual_ids = [
        str(item)
        for item in (slot.get("visual_ids") or [])
        if str(item or "").strip()
    ]
    min_words = sum(max(0, _safe_int(lane.get("min_words"), 0)) for lane in lanes)
    min_native_units = sum(max(0, _safe_int(lane.get("min_native_units"), 0)) for lane in lanes)
    target_words = _slot_target_words(slot_id, min_words, visual_ids=visual_ids)
    lane_plan = []
    for lane in lanes:
        lane_id = str(lane.get("lane_id") or lane.get("data_lane") or "").strip()
        if not lane_id:
            continue
        lane_plan.append({
            "lane_id": lane_id,
            "role": lane.get("role"),
            "min_words": max(0, _safe_int(lane.get("min_words"), 0)),
            "min_native_units": max(0, _safe_int(lane.get("min_native_units"), 0)),
            "visual_ids": [str(v) for v in (lane.get("visual_ids") or []) if str(v or "").strip()],
            "visual_layout_variant": lane.get("visual_layout_variant"),
            "fill_instruction": lane.get("fill_instruction") or _lane_fill_instruction(
                lane_id,
                str(lane.get("role") or ""),
                [str(v) for v in (lane.get("visual_ids") or []) if str(v or "").strip()],
            ),
        })
    return {
        "slot_id": slot_id,
        "panel_role": slot.get("panel_role") or slot.get("role") or slot_id,
        "title": slot.get("title") or str(slot_id).replace("_", " ").title(),
        "target_words": target_words,
        "min_lane_words": min_words,
        "min_native_units": max(1, min_native_units),
        "required_content_modes": _slot_required_content_modes(slot_id, visual_ids=visual_ids),
        "visual_ids": visual_ids,
        "source_aspect": slot.get("source_aspect"),
        "visual_layout_variant": slot.get("visual_layout_variant"),
        "lane_plan": lane_plan,
        "html_recipe": _slot_html_recipe(slot_id, visual_ids=visual_ids),
    }


def _slot_target_words(slot_id: str, min_words: int, *, visual_ids: list[str]) -> int:
    if slot_id == "synthesis_takeaway":
        return max(42, min(78, min_words + 14))
    if visual_ids:
        return max(38, min(78, min_words + 14))
    if any(token in slot_id for token in ("results", "ablation", "analysis")):
        return max(64, min(110, min_words + 18))
    return max(70, min(118, min_words + 20))


def _slot_required_content_modes(slot_id: str, *, visual_ids: list[str]) -> list[str]:
    modes = ["source_backed_text", "local_takeaway"]
    if visual_ids:
        modes.extend(["source_visual_or_table", "caption_interpretation"])
    if any(token in slot_id for token in ("result", "benchmark", "ablation", "evidence")):
        modes.append("native_table_or_result_band")
    elif any(token in slot_id for token in ("method", "model", "architecture")):
        modes.append("method_pipeline_or_model_card")
    elif "limitation" in slot_id or "future" in slot_id:
        modes.append("limitation_future_rows")
    elif "synthesis" in slot_id:
        modes.append("synthesis_takeaway_rows")
    else:
        modes.append("native_claim_or_metric_rows")
    out: list[str] = []
    for mode in modes:
        if mode not in out:
            out.append(mode)
    return out


def _slot_html_recipe(slot_id: str, *, visual_ids: list[str]) -> str:
    if visual_ids:
        return (
            "Use heading + one or more bound source figures/tables as the panel subject + "
            "short source-backed readout + takeaway. Author each figure/table itself and its own "
            "explanatory text as a separate browser flow unit with float/shape-outside; "
            "do not create an empty visual placeholder/bbox before placing the source asset; "
            "never split one source asset from its text into media-grid, side-stack, two-up, "
            "or separate image/text wrappers. "
            "For ingest_table_* source crops, keep the exact source id on a floated "
            "data-block-kind=\"table\" figure wrapper; native tables are supplemental summaries. "
            "When multiple visual_ids are assigned, use multiple direct-child "
            ".figure-flow-unit/.source-flow-unit blocks, one per source, not a support-strip, "
            "figure-strip, media-row, gallery wrapper, or one shared text flow."
        )
    if "result" in slot_id or "benchmark" in slot_id:
        return "Use heading + result claim + bound source benchmark/table crop as the main evidence + compact comparison table rows + short result discussion + takeaway sentence."
    if "method" in slot_id or "model" in slot_id:
        return "Use heading + bound source method visual/table plus compact pipeline labels, reading notes, and takeaway."
    if "ablation" in slot_id or "analysis" in slot_id:
        return "Use heading + bound source analysis visual/table plus compact comparison table rows, concise visual interpretation, and takeaway sentence."
    if "synthesis" in slot_id:
        return "Use a compact heading and dense labeled takeaway rows across the full strip."
    return "Use heading + source-backed claim + edited body + native information rows + takeaway."


def _contract_authored_html_skeleton(
    contract: dict[str, Any],
    *,
    color_system: dict[str, Any] | None = None,
) -> dict[str, str]:
    slots = contract.get("slots") if isinstance(contract.get("slots"), list) else []
    if not slots:
        return {}
    grid = contract.get("grid") if isinstance(contract.get("grid"), dict) else {}
    cols = max(1, _safe_int(grid.get("cols"), 3))
    rows = max(1, _safe_int(grid.get("rows"), 2))
    title_slot = next(
        (slot for slot in slots if str(slot.get("slot_id") or "") == "title_meta"),
        slots[0],
    )
    title_bbox = title_slot.get("bbox") if isinstance(title_slot.get("bbox"), dict) else {}
    header_h = max(1, _safe_int(title_bbox.get("h"), 230))
    html_parts = [
        (
            '<main class="paper-poster authored-css-poster flow-poster" '
            'data-layout-mode="panel-flow" '
            f'style="--poster-cols:{cols};--poster-rows:{rows};--header-h:{header_h}px;">'
        )
    ]
    panel_parts: list[str] = []
    for slot in slots:
        slot_id = str(slot.get("slot_id") or "slot").strip()
        role = str(slot.get("panel_role") or slot.get("role") or slot_id).strip()
        min_words = sum(
            max(0, _safe_int(lane.get("min_words"), 0))
            for lane in (slot.get("child_lanes") or [])
            if isinstance(lane, dict)
        )
        min_native_units = sum(
            max(0, _safe_int(lane.get("min_native_units"), 0))
            for lane in (slot.get("child_lanes") or [])
            if isinstance(lane, dict)
        )
        visual_ids = [
            str(v) for v in (slot.get("visual_ids") or [])
            if str(v or "").strip()
        ]
        visual_attr = (
            f' data-visual-ids="{escape(",".join(visual_ids))}"'
            if visual_ids else ""
        )
        tag = "header" if slot_id == "title_meta" else "article"
        class_name = "poster-header flow-body" if slot_id == "title_meta" else "flow-panel flow-body"
        part = (
            f'<{tag} class="{class_name}" data-slot-id="{escape(slot_id)}" '
            f'data-panel-role="{escape(role)}" data-layout-mode="panel-flow" '
            f'data-block-id="{escape(_safe_dom_id(slot_id, "panel"))}" '
            f'data-flow-region="{escape(slot_id)}_flow" '
            f'data-min-words="{min_words}" data-min-native-units="{min_native_units}"'
            f'{visual_attr}>'
            f'<!-- {escape(_skeleton_flow_comment(slot))} -->'
            f'</{tag}>'
        )
        if slot_id == "title_meta":
            html_parts.append(part)
        else:
            panel_parts.append(part)
    html_parts.append('<section class="poster-grid" data-layout-region="main_panels">')
    html_parts.extend(panel_parts)
    html_parts.append("</section>")
    html_parts.append("</main>")
    return {
        "version": 1,
        "html": "\n".join(html_parts),
        "css": _contract_skeleton_css(color_system),
        "instruction": (
            "Use this DOM/CSS as a starting point. Replace flow comments with final poster content, "
            "keep data-slot-id/data-panel-role panel roots and data-source-id/data-layer-id visual "
            "bindings, and author each source figure/table itself plus its explanatory text directly "
            "inside the panel root as one browser-native flow DOM. Do not add an empty visual "
            "placeholder/bbox before placing the asset, an inner .slot-flow/.flow-body, "
            "position:absolute panel lanes, media grids, side stacks, or two-up image/text wrappers."
        ),
    }


def _contract_editorial_html_skeleton(
    contract: dict[str, Any],
    *,
    color_system: dict[str, Any] | None = None,
) -> dict[str, str]:
    if str(contract.get("mode") or "") != "editorial_flow_poster":
        return {}
    column_roles = contract.get("column_roles") if isinstance(contract.get("column_roles"), list) else []
    if not column_roles:
        column_roles = [
            {"column_id": "left_story", "title": "The Motivation"},
            {"column_id": "middle_method", "title": "The Method"},
            {"column_id": "right_results", "title": "The Results"},
        ]
    html_parts = [
        '<main class="paper-poster authored-css-poster editorial-poster" data-layout-mode="editorial-flow">',
        (
            '<header class="poster-header editorial-header" data-block-id="title_meta" '
            'data-role="identity_header">'
            '<!-- Fill with exactly these three rows only: paper title, authors, and plain-text school/institution/company names. -->'
            '</header>'
        ),
        '<div class="poster-columns" data-layout-region="editorial_columns">',
    ]
    for idx, column in enumerate(column_roles[:3], start=1):
        column_id = _safe_dom_id(column.get("column_id") or f"column_{idx}", f"column_{idx}")
