def _skeleton_flow_comment(slot: dict[str, Any]) -> str:
    slot_id = str(slot.get("slot_id") or "").strip()
    lanes = [lane for lane in (slot.get("child_lanes") or []) if isinstance(lane, dict)]
    min_words = sum(max(0, _safe_int(lane.get("min_words"), 0)) for lane in lanes)
    min_native_units = sum(max(0, _safe_int(lane.get("min_native_units"), 0)) for lane in lanes)
    lane_roles = [
        str(lane.get("role") or lane.get("lane_id") or lane.get("data_lane") or "").strip()
        for lane in lanes
        if str(lane.get("role") or lane.get("lane_id") or lane.get("data_lane") or "").strip()
    ]
    if slot_id == "title_meta":
        pieces = [
            f"fill {slot_id} with paper identity metadata only",
            "no thesis, tagline, right-side summary, or source-backed poster descriptor",
        ]
    else:
        pieces = [f"fill {slot_id} with final source-backed poster content"]
    if min_words:
        pieces.append(f"target at least {min_words} visible words when source supports it")
    if min_native_units:
        pieces.append(
            f"include at least {min_native_units} native/source unit using a bound figure/table, "
            "native table, compact comparison table rows, figure label, method notes, "
            "compact pipeline stage, or source-grounded bullets"
        )
    if lane_roles:
        pieces.append("content hints: " + ", ".join(lane_roles))
    visual_ids = [str(v) for v in (slot.get("visual_ids") or []) if str(v or "").strip()]
    if visual_ids:
        pieces.append(
            "bind each source figure/table with data-source-id or data-layer-id inside its own direct-child .figure-flow-unit/.source-flow-unit; the source asset itself is the normal-flow object, not content inserted into an empty bbox; float .flow-asset left/right with shape-outside so local prose wraps around that one asset; do not use media-grid, side-stack, two-up, or separate image/text wrappers inside the source flow unit"
        )
    if len(visual_ids) >= 2:
        pieces.append(
            "for multi-source panels, place each source as its own direct-child "
            ".figure-flow-unit/.source-flow-unit block under the panel root; do not wrap "
            "sources in .support-strip, .figure-strip, gallery, media-row, any grid/flex strip, "
            "or one shared text flow"
        )
    table_ids = [source_id for source_id in visual_ids if source_id.startswith("ingest_table_")]
    if table_ids:
        pieces.append(
            "for source tables preserve the exact ingest_table_* id on a floated "
            '<figure class="flow-figure source-table float-left/right" '
            'data-block-kind="table" data-source-id="..." data-layer-id="..."> wrapper; '
            "native tables may summarize but must not replace the bound source table"
        )
    return "; ".join(pieces)


def _safe_dom_id(value: Any, fallback: str) -> str:
    text = re.sub(r"[^a-zA-Z0-9_-]+", "_", str(value or "").strip()).strip("_")
    return text or fallback


