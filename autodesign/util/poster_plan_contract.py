def _unique_source_ids(values: list[str], *, forbidden: set[str] | None = None) -> list[str]:
    out: list[str] = []
    blocked = forbidden or set()
    for value in values:
        item = str(value or "").strip()
        if item and item not in blocked and item not in out:
            out.append(item)
    return out


def _contract_source_id_allowed(
    layer_id: str,
    rendered_layers: dict[str, dict[str, Any]],
    forbidden_source_ids: set[str],
    *,
    allow_reserve: bool = False,
) -> bool:
    layer_id = str(layer_id or "").strip()
    if not layer_id or layer_id in forbidden_source_ids or not _is_source_visual_id(layer_id):
        return False
    if layer_id not in rendered_layers:
        return False
    rec = rendered_layers.get(layer_id)
    if isinstance(rec, dict):
        tier = _contract_source_visual_tier(layer_id, rec)
        if tier != "eligible" and not (allow_reserve and tier == "reserve_unmatched"):
            return False
    return True


def _filter_contract_source_ids(
    values: list[str],
    rendered_layers: dict[str, dict[str, Any]],
    forbidden_source_ids: set[str],
    *,
    allow_reserve: bool = False,
) -> list[str]:
    out: list[str] = []
    for value in values:
        layer_id = str(value or "").strip()
        if (
            _contract_source_id_allowed(
                layer_id,
                rendered_layers,
                forbidden_source_ids,
                allow_reserve=allow_reserve,
            )
            and layer_id not in out
        ):
            out.append(layer_id)
    return out


def _dedupe_contract_source_ids(
    values: list[str],
    rendered_layers: dict[str, dict[str, Any]],
    *,
    existing_ids: list[str] | None = None,
) -> list[str]:
    out: list[str] = []
    existing = [str(item or "").strip() for item in (existing_ids or []) if str(item or "").strip()]
    for value in values:
        layer_id = str(value or "").strip()
        if not layer_id:
            continue
        if _contract_source_id_matches_any(layer_id, existing, rendered_layers):
            continue
        if _contract_source_id_matches_any(layer_id, out, rendered_layers):
            continue
        out.append(layer_id)
    return out


def _contract_source_id_matches_any(
    layer_id: str,
    existing_ids: list[str],
    rendered_layers: dict[str, dict[str, Any]],
) -> bool:
    return any(
        _contract_source_ids_are_duplicates(existing_id, layer_id, rendered_layers)
        for existing_id in existing_ids
    )


def _contract_source_ids_are_duplicates(
    a_id: str,
    b_id: str,
    rendered_layers: dict[str, dict[str, Any]],
) -> bool:
    if a_id == b_id:
        return True
    a = rendered_layers.get(a_id) or {}
    b = rendered_layers.get(b_id) or {}
    for key in (
        "source_group_id",
        "output_sha256",
        "sha256",
        "image_sha256",
        "source_sha256",
        "output_file",
        "src_path",
    ):
        a_val = str(a.get(key) or "").strip()
        b_val = str(b.get(key) or "").strip()
        if a_val and b_val and a_val == b_val:
            return True
    a_page = _safe_int(a.get("source_page") or a.get("page"), -1)
    b_page = _safe_int(b.get("source_page") or b.get("page"), -2)
    if a_page < 0 or a_page != b_page:
        return False
    a_xref = str(a.get("source_image_xref") or a.get("image_xref") or "").strip()
    b_xref = str(b.get("source_image_xref") or b.get("image_xref") or "").strip()
    if a_xref and b_xref and a_xref == b_xref:
        return True
    a_bbox = _source_pdf_bbox_tuple(a)
    b_bbox = _source_pdf_bbox_tuple(b)
    if not a_bbox or not b_bbox:
        return False
    iou, coverage = _source_bbox_overlap_stats(a_bbox, b_bbox)
    return iou >= 0.72 or coverage >= 0.88


def _source_pdf_bbox_tuple(rec: dict[str, Any]) -> tuple[float, float, float, float] | None:
    for key in ("source_bbox_pdf_points", "source_bbox", "pdf_bbox", "bbox"):
        value = rec.get(key)
        if isinstance(value, (list, tuple)) and len(value) >= 4:
            try:
                x0, y0, x1, y1 = [float(v) for v in value[:4]]
            except (TypeError, ValueError):
                continue
            if x1 > x0 and y1 > y0:
                return x0, y0, x1, y1
        if isinstance(value, dict):
            try:
                x = float(value.get("x"))
                y = float(value.get("y"))
                w = float(value.get("w"))
                h = float(value.get("h"))
            except (TypeError, ValueError):
                continue
            if w > 0 and h > 0:
                return x, y, x + w, y + h
    return None


def _source_bbox_overlap_stats(
    a: tuple[float, float, float, float],
    b: tuple[float, float, float, float],
) -> tuple[float, float]:
    ax0, ay0, ax1, ay1 = a
    bx0, by0, bx1, by1 = b
    ix0 = max(ax0, bx0)
    iy0 = max(ay0, by0)
    ix1 = min(ax1, bx1)
    iy1 = min(ay1, by1)
    if ix1 <= ix0 or iy1 <= iy0:
        return 0.0, 0.0
    inter = (ix1 - ix0) * (iy1 - iy0)
    a_area = max(0.0, (ax1 - ax0) * (ay1 - ay0))
    b_area = max(0.0, (bx1 - bx0) * (by1 - by0))
    union = a_area + b_area - inter
    iou = inter / union if union > 0 else 0.0
    coverage = inter / min(a_area, b_area) if min(a_area, b_area) > 0 else 0.0
    return iou, coverage


