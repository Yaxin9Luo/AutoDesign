def _as_bbox(value: Any) -> dict[str, int] | None:
    if not isinstance(value, dict):
        return None
    try:
        bbox = {key: int(float(value[key])) for key in ("x", "y", "w", "h")}
    except Exception:
        return None
    if bbox["w"] <= 0 or bbox["h"] <= 0:
        return None
    return bbox


def _bbox_area(value: Any, cw: int, ch: int) -> float:
    return _bbox_area_in_region(value, cw, ch, {"x": 0, "y": 0, "w": cw, "h": ch})


def _bbox_area_in_region(value: Any, cw: int, ch: int, region: dict[str, Any]) -> float:
    bbox = _as_bbox(value)
    if not bbox:
        return 0.0
    x0 = max(0, min(cw, bbox["x"]))
    y0 = max(0, min(ch, bbox["y"]))
    x1 = max(0, min(cw, bbox["x"] + bbox["w"]))
    y1 = max(0, min(ch, bbox["y"] + bbox["h"]))
    rx0 = max(0, min(cw, _safe_int(region.get("x"), 0)))
    ry0 = max(0, min(ch, _safe_int(region.get("y"), 0)))
    rx1 = max(0, min(cw, rx0 + _safe_int(region.get("w"), cw)))
    ry1 = max(0, min(ch, ry0 + _safe_int(region.get("h"), ch)))
    return max(0, min(x1, rx1) - max(x0, rx0)) * max(0, min(y1, ry1) - max(y0, ry0))


def _bbox_intersection_area(a: dict[str, int], b: dict[str, int]) -> float:
    return max(0, min(a["x"] + a["w"], b["x"] + b["w"]) - max(a["x"], b["x"])) * max(
        0,
        min(a["y"] + a["h"], b["y"] + b["h"]) - max(a["y"], b["y"]),
    )


def _axis_overlap(a0: int, a1: int, b0: int, b1: int) -> int:
    return max(0, min(a1, b1) - max(a0, b0))


def _word_count(text: str) -> int:
    return len(re.findall(r"[^\W_]+", str(text or ""), flags=re.UNICODE))


def _safe_int(value: Any, default: int) -> int:
    try:
        return int(float(value))
    except Exception:
        return default


def _safe_float(value: Any, default: float) -> float:
    try:
        return float(value)
    except Exception:
        return default
