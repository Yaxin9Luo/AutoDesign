def _brief_source_backed_text_metrics(brief_sections: dict[str, dict[str, Any]]) -> dict[str, Any]:
    source_backed_units = 0
    source_backed_sections: set[str] = set()
    abstract_units = 0
    total_units = 0
    for section_id, section in brief_sections.items():
        for bullet in section.get("bullets") or []:
            if not isinstance(bullet, dict):
                continue
            text = str(bullet.get("text") or "").strip()
            if not text:
                continue
            total_units += 1
            source = str(bullet.get("source") or bullet.get("claim_id") or "").strip()
            source_ids = [str(item) for item in (bullet.get("source_ids") or []) if str(item or "").strip()]
            if source or source_ids:
                source_backed_units += 1
                source_backed_sections.add(section_id)
            if source == "manifest.abstract" or any(str(item).startswith("manifest.abstract") for item in source_ids):
                abstract_units += 1
    return {
        "text_unit_count": total_units,
        "source_backed_text_unit_count": source_backed_units,
        "source_backed_section_count": len(source_backed_sections),
        "abstract_sourced_text_unit_count": abstract_units,
        "source_backed_section_ids": sorted(source_backed_sections),
    }


def _brief_abstract_dump_risk(brief_sections: dict[str, dict[str, Any]]) -> dict[str, Any]:
    risky: list[dict[str, Any]] = []
    for section_id, section in brief_sections.items():
        for bullet in section.get("bullets") or []:
            if not isinstance(bullet, dict):
                continue
            text = str(bullet.get("text") or "").strip()
            if not text:
                continue
            source = str(bullet.get("source") or "").strip()
            word_count = _word_count(text)
            if word_count >= 58 or (source == "manifest.abstract" and word_count >= 34):
                risky.append({
                    "section_id": section_id,
                    "source": source,
                    "word_count": word_count,
                    "text": text[:180],
                })
    return {
        "abstract_dump_risk_count": len(risky),
        "examples": risky[:5],
    }


def _dense_narrative_role_coverage(brief_sections: dict[str, dict[str, Any]]) -> dict[str, Any]:
    required = {
        "motivation": ("motivation", "problem"),
        "contribution": ("contribution", "principal"),
        "model_method": ("model", "model_card", "method", "pipeline", "architecture"),
        "evidence": ("result", "results", "table", "benchmark", "evidence"),
        "analysis": ("analysis", "ablation", "training", "data"),
        "limitations": ("limitation", "future"),
        "provenance": ("footer", "provenance", "source", "code", "citation"),
    }
    haystack_by_section = {
        section_id: " ".join([
            section_id,
            str(section.get("title") or ""),
            str(section.get("purpose") or ""),
            " ".join(str((bullet or {}).get("text") or "") for bullet in (section.get("bullets") or []) if isinstance(bullet, dict)),
        ]).lower()
        for section_id, section in brief_sections.items()
    }
    hits: list[str] = []
    for role, tokens in required.items():
        if any(any(token in text for token in tokens) for text in haystack_by_section.values()):
            hits.append(role)
    return {
        "required_roles": list(required.keys()),
        "hits": hits,
        "missing": [role for role in required if role not in hits],
        "coverage": round(len(hits) / max(1, len(required)), 3),
    }


