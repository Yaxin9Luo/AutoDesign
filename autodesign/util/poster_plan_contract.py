def _contract_native_information_targets(
    raw: Any,
    *,
    reference_profile: str,
) -> dict[str, Any]:
    if reference_profile not in {*_DENSE_REFERENCE_PROFILES, "visual_evidence_wall"}:
        return {}
    raw = raw if isinstance(raw, dict) else {}
    if reference_profile == _EDITORIAL_FLOW_PROFILE:
        min_native_default = 10
        target_native_default = 16
        min_words_default = 360
        target_words_default = 560
        min_panels_default = 3
        target_panels_default = 6
    elif reference_profile == "visual_evidence_wall":
        min_native_default = 8
        target_native_default = 14
        min_words_default = 420
        target_words_default = 650
        min_panels_default = 6
        target_panels_default = 8
    else:
        min_native_default = 14
        target_native_default = 22
        min_words_default = 520
        target_words_default = 850
        min_panels_default = 6
        target_panels_default = 8
    if reference_profile in _DENSE_REFERENCE_PROFILES and not isinstance(raw, dict):
        return {}
    min_native = max(
        min_native_default,
        _safe_int(raw.get("min_native_information_units"), min_native_default),
    )
    target_native = max(
        target_native_default,
        min_native,
        _safe_int(
            raw.get("target_native_information_units")
            or raw.get("target_native_information_unit_count"),
            target_native_default,
        ),
    )
    min_words = min(
        620 if reference_profile == _EDITORIAL_FLOW_PROFILE else 760 if reference_profile == "research_synthesis_dense" else 620,
        max(
            min_words_default,
            _safe_int(raw.get("min_visible_words"), min_words_default),
        ),
    )
    target_words = min(
        780 if reference_profile == _EDITORIAL_FLOW_PROFILE else 950 if reference_profile == "research_synthesis_dense" else 780,
        max(
            target_words_default,
            min_words,
            _safe_int(
                raw.get("target_visible_words")
                or raw.get("target_visible_text_word_count"),
                target_words_default,
            ),
        ),
    )
    return {
        "min_panel_count": max(
            min_panels_default,
            _safe_int(raw.get("min_panel_count"), min_panels_default),
        ),
        "target_panel_count": max(
            target_panels_default,
            _safe_int(raw.get("target_panel_count"), target_panels_default),
        ),
        "min_native_information_units": min_native,
        "target_native_information_units": target_native,
        "min_visible_words": min_words,
        "target_visible_words": target_words,
        "required_units": [
            str(item) for item in (raw.get("required_units") or [])
            if str(item or "").strip()
        ],
        "panel_jobs": [
            str(item) for item in (raw.get("panel_jobs") or [])
            if str(item or "").strip()
        ],
        "text_synthesis_targets": (
            raw.get("text_synthesis_targets")
            if isinstance(raw.get("text_synthesis_targets"), dict)
            else {}
        ),
        "acceptance_focus": [
            str(item) for item in (raw.get("acceptance_focus") or [])
            if str(item or "").strip()
        ],
        "negative_guidance": [
            str(item) for item in (raw.get("negative_guidance") or [])
            if str(item or "").strip()
        ],
    }


