def _dense_keyword_family_count(haystack: str, tokens: tuple[str, ...]) -> int:
    hits = sum(1 for token in tokens if token and token in haystack)
    if hits >= 5:
        return 3
    if hits >= 3:
        return 2
    if hits >= 1:
        return 1
    return 0


def _dense_formula_like_count(text_layers: list[dict[str, Any]], haystack: str) -> int:
    formula_markers = (
        "=", "∑", "Σ", "\\sum", "lambda", "λ", "loss", "objective", "regularizer",
        "gradient", "probability", "p(", "argmax", "argmin",
    )
    formula_layers = 0
    for layer in text_layers:
        text = str(layer.get("text") or "")
        identity = _layer_identity(layer)
        if str(layer.get("kind") or "").lower() == "formula" or "formula" in identity:
            formula_layers += 1
            continue
        marker_hits = sum(1 for marker in formula_markers if marker and marker.lower() in text.lower())
        if marker_hits >= 2 or ("=" in text and any(ch.isdigit() for ch in text)):
            formula_layers += 1
    if formula_layers:
        return min(5, formula_layers)
    return min(3, _dense_keyword_family_count(haystack, formula_markers))


def _dense_native_chart_like_layer(layer: dict[str, Any]) -> bool:
    kind = str(layer.get("kind") or "").lower()
    if kind == "chart":
        return True
