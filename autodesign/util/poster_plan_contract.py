def _contract_color_css_declarations(color_system: dict[str, Any] | None) -> str:
    normalized = _normalize_contract_color_system(color_system)
    if not normalized:
        normalized = _contract_color_system({})
    css_vars = normalized.get("css_variables") if isinstance(normalized.get("css_variables"), dict) else {}
    return "".join(
        f"{css_var}:{css_vars[css_var]};"
        for css_var in _COLOR_CSS_VAR_BY_ROLE.values()
        if css_var in css_vars
    )


def _normalize_contract_color_system(value: Any) -> dict[str, Any]:
    if not isinstance(value, dict):
        return {}
    allowed_from_value = _unique_contract_hexes(
        value.get("allowed_hexes") if isinstance(value.get("allowed_hexes"), list) else []
    )
    roles = _valid_hex_mapping(value.get("roles"))
    css_variables = _valid_hex_mapping(value.get("css_variables"))
    if not roles and allowed_from_value:
        roles = _roles_from_allowed_hexes(allowed_from_value)
    if roles and not css_variables:
        css_variables = {
            css_var: roles[role]
            for role, css_var in _COLOR_CSS_VAR_BY_ROLE.items()
            if role in roles
        }
    if css_variables and not roles:
        inverse = {css_var: role for role, css_var in _COLOR_CSS_VAR_BY_ROLE.items()}
        roles = {
            inverse[css_var]: hex_value
            for css_var, hex_value in css_variables.items()
            if css_var in inverse
        }
    if not roles:
        roles = dict(_FALLBACK_COLOR_ROLES)
    if not css_variables:
        css_variables = {
            css_var: roles[role]
            for role, css_var in _COLOR_CSS_VAR_BY_ROLE.items()
            if role in roles
        }
    allowed = _unique_contract_hexes(
        allowed_from_value or list(css_variables.values())
    )
    if not allowed:
        allowed = _unique_contract_hexes(list(roles.values()))
    if not allowed:
        return {}
    normalized = dict(value)
    normalized["roles"] = roles
    normalized["css_variables"] = css_variables
    normalized["allowed_hexes"] = allowed
    normalized["palette_id"] = str(normalized.get("palette_id") or "bright_cobalt")
    normalized["palette_name"] = str(normalized.get("palette_name") or "Cardinal Red")
    return normalized


def _roles_from_allowed_hexes(allowed_hexes: list[str]) -> dict[str, str]:
    fallback = dict(_FALLBACK_COLOR_ROLES)
    roles = {
        "background": allowed_hexes[0] if len(allowed_hexes) > 0 else fallback["background"],
        "text": allowed_hexes[1] if len(allowed_hexes) > 1 else fallback["text"],
        "primary": allowed_hexes[2] if len(allowed_hexes) > 2 else fallback["primary"],
        "secondary": allowed_hexes[3] if len(allowed_hexes) > 3 else fallback["secondary"],
        "accent": allowed_hexes[4] if len(allowed_hexes) > 4 else (
            allowed_hexes[2] if len(allowed_hexes) > 2 else fallback["accent"]
        ),
    }
    roles["header_text"] = fallback["header_text"]
    roles["bar"] = roles["primary"]
    return roles


def _valid_hex_mapping(value: Any) -> dict[str, str]:
    if not isinstance(value, dict):
        return {}
    out: dict[str, str] = {}
    for key, raw in value.items():
        text = str(raw or "").strip().upper()
        if re.fullmatch(r"#[0-9A-F]{6}", text):
            out[str(key)] = text
    return out


def _unique_contract_hexes(values: Any) -> list[str]:
    out: list[str] = []
    for value in values or []:
        text = str(value or "").strip().upper()
        if re.fullmatch(r"#[0-9A-F]{6}", text) and text not in out:
            out.append(text)
    return out


