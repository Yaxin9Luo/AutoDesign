def _section_has_grounded_content(section: dict[str, Any]) -> bool:
    for bullet in section.get("bullets") or []:
        if not isinstance(bullet, dict):
            continue
        text = str(bullet.get("text") or "").strip()
        source_ids = bullet.get("source_ids") if isinstance(bullet.get("source_ids"), list) else []
        source = str(bullet.get("source") or bullet.get("claim_id") or "").strip()
        if source_ids:
            source = source or str(source_ids[0])
