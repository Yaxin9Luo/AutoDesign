const DICTIONARIES: Partial<Record<UiLanguage, Record<string, string>>> = {
  zh: ZH,
  es: { ...ES, ...ES_EXTRA },
  fr: { ...FR, ...FR_EXTRA },
  de: { ...DE, ...DE_EXTRA },
  ru: { ...RU, ...RU_EXTRA },
  ko: { ...KO, ...KO_EXTRA },
  ja: { ...JA, ...JA_EXTRA },
  ar: { ...AR, ...AR_EXTRA },
};

export function translate(lang: UiLanguage, text: string, params?: Params): string {
  const template = DICTIONARIES[lang]?.[text] ?? text;
  if (!params) return template;
  return Object.entries(params).reduce(
    (out, [key, value]) => out.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function languageLabel(lang: UiLanguage): string {
  return LANGUAGE_OPTIONS.find((option) => option.id === lang)?.nativeLabel ?? "English";
}

export function languageShortLabel(lang: UiLanguage): string {
  return LANGUAGE_OPTIONS.find((option) => option.id === lang)?.shortLabel ?? "EN";
}

export function languageDirection(lang: UiLanguage): "ltr" | "rtl" {
  return LANGUAGE_OPTIONS.find((option) => option.id === lang)?.dir ?? "ltr";
}

export function isSupportedLanguage(value: unknown): value is UiLanguage {
  return typeof value === "string" && LANGUAGE_OPTIONS.some((option) => option.id === value);
}
